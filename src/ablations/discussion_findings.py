"""Exploratory "where does each model help?" analyses for the Discussion.

Four analyses, all on the fixed test set, all reusing already-trained models
(no retraining, no test-set tuning):

  1. Subgroup interaction scan. For every pair of models (A, B) and every
     binary patient subgroup defined from PRE-INDEX information only (age,
     sex, CCI, index cardiometabolic condition, ICU history, history density,
     history span, recency, data modalities present, race), compute
         interaction = (AUC_A - AUC_B | in subgroup) - (AUC_A - AUC_B | rest)
     per disease-horizon cell and per seed. Same consistency bar as
     cold_start_stratification.py (a cell counts if >=4/5 seeds agree on
     sign), sign test across cells, Benjamini-Hochberg across the whole scan.
     The thin/rich history split from the paper is one row of this scan, so
     it doubles as a check that this script reproduces that result.
     Also reports the within-subgroup margin itself, so "the GNN helps more
     in X" is never confused with "the GNN beats Cox in X".

  2. Rescued-positive profiling. Among true positives (3-year horizon, all
     five diseases pooled), find patients that model A ranks much higher than
     model B (and vice versa), then compare their pre-index profiles and test
     which medical concepts are enriched in A-favoured vs B-favoured patients
     (Fisher exact, BH-corrected).

  3. "Which disease first?" Among patients with an observed event within 5
     years, how often does each model's highest (within-disease percentile)
     risk point to the disease that actually happened? This is the stated
     goal of the paper and is where a jointly-trained competing-risks head
     could plausibly beat five separately-fit Cox models.

  4. Complementarity. Rank-averaging Cox with each other model; if Cox+GNN
     gains more than Cox+XGBoost (a same-information control), the graph
     model carries signal the fixed-feature baselines do not.

Everything here is exploratory and hypothesis-generating: many subgroups x
model pairs are scanned, and per-subgroup positive counts can be small.
Report counts alongside every number, and prefer patterns that hold across
cells and seeds over any single cell.

Inputs (whatever exists is used; missing models are skipped with a warning):
  baselines_survival[_seedN]/predictions_test.csv   Cox (fixed), XGBoost
  tgn_survival[_seedN]/predictions_test.csv          TKG-Transformer
    (override the directory prefix with TKG_TGN_DIR_PREFIX if the tuned
     model was written elsewhere)
  patient_gnn_survival[_seedN]/best_model.pt         patient-graph GNN,
    regenerated by pure inference and cached to
    stats/discussion/pg_test_scores.parquet

Outputs: tkg_output/stats/discussion/*.csv and summary.txt
"""
