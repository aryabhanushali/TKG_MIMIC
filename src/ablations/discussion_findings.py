def _load_baselines() -> dict:
    out = {"cox": {}, "xgb": {}}
    for seed in SEEDS:
        path = os.path.join(_seed_dir("baselines_survival", seed), "predictions_test.csv")
        if not os.path.exists(path):
            continue
        df = pd.read_csv(path).set_index("subject_id")
        if seed == 42:  # Cox is deterministic; fit once
            out["cox"][42] = {(c, h): df[f"cox_risk_{c}"] for c in CAUSES for h in HORIZON_DAYS}
        out["xgb"][seed] = {(c, h): df[f"xgb_surv_risk_{c}"] for c in CAUSES for h in HORIZON_DAYS}
    return out


def _load_tkg() -> dict:
    out = {}
    for seed in SEEDS:
        path = os.path.join(_seed_dir(TGN_PREFIX, seed), "predictions_test.csv")
        if os.path.exists(path):
            df = pd.read_csv(path).set_index("subject_id")
            out[seed] = {(c, h): df[f"cif_{c}_at_{h}d"] for c in CAUSES for h in HORIZON_DAYS}
    return out


def _load_pg() -> dict:
    # patient_graph_gnn.py now writes predictions_test.csv itself; prefer it
    # (also the only option for pooled EHRSHOT CV dirs, which have no checkpoints).
    direct = {}
    for seed in SEEDS:
        path = os.path.join(_seed_dir("patient_gnn_survival", seed), "predictions_test.csv")
        if os.path.exists(path):
            df = pd.read_csv(path).set_index("subject_id")
            direct[seed] = {(c, h): df[f"cif_{c}_at_{h}d"] for c in CAUSES for h in HORIZON_DAYS}
    if direct:
        return direct
    cache = os.path.join(OUT_DIR, "pg_test_scores.parquet")
    if not os.path.exists(cache):
        ckpts = [os.path.join(_seed_dir("patient_gnn_survival", s), "best_model.pt") for s in SEEDS]
        if not all(os.path.exists(p) for p in ckpts):
            return {}
        from src.ablations.cold_start_stratification import _load_patient_graph_probs_all_seeds
        _load_patient_graph_probs_all_seeds().to_parquet(cache, index=False)
    df = pd.read_parquet(cache).set_index("subject_id")
    return {seed: {(c, h): df[f"pg_cif_{c}_at_{h}d_seed{seed}"] for c in CAUSES for h in HORIZON_DAYS}
            for seed in SEEDS}


def load_scores() -> dict:
    scores = _load_baselines()
    scores["tkg"] = _load_tkg()
    scores["pg"] = _load_pg()
    for m in list(scores):
        if not scores[m]:
            print(f"  WARNING: no test predictions found for {MODEL_LABEL[m]} -- skipped")
            del scores[m]
        else:
            print(f"  {MODEL_LABEL[m]}: seeds {sorted(scores[m])}")
    return scores


