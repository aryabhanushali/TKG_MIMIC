def _race_bucket(race) -> str:
    if pd.isna(race):
        return "Unknown"
    r = str(race).upper()
    if "WHITE" in r:
        return "White"
    if "BLACK" in r:
        return "Black"
    if "HISPANIC" in r or "LATINO" in r:
        return "Hispanic/Latino"
    if "ASIAN" in r:
        return "Asian"
    if any(k in r for k in ("UNKNOWN", "UNABLE", "DECLINED")):
        return "Unknown"
    return "Other"


def build_descriptors(labels: pd.DataFrame) -> pd.DataFrame:
    """One row per patient (all splits). Every column uses pre-index data only."""
    static = pd.read_csv(os.path.join(MODELING_DIR, "static_features.csv"))
    cohort = pd.read_csv(os.path.join(OUTPUT_DIR, "cohort.csv"), usecols=["subject_id", "cardiometa_types"])
    ev = read_events_table(["subject_id", "concept_node_idx", "fact_type", "relative_days"])

    g = ev.groupby("subject_id")
    d = pd.DataFrame({
        "n_facts": g.size(),
        "n_concepts": g["concept_node_idx"].nunique(),
        "history_span_days": -g["relative_days"].min(),
        "frac_recent_90d": g["relative_days"].apply(lambda r: (r >= -90).mean()),
    })
    # Facts strictly before the index admission window, i.e. any earlier encounter at all.
    d["has_prior_encounter"] = g["relative_days"].apply(lambda r: bool((r < -30).any()))
    modality = pd.crosstab(ev["subject_id"], ev["fact_type"]) > 0
    for ft in ["lab", "prescription", "omr_bp", "vital", "procedure"]:
        if ft in modality:
            d[f"has_{ft}"] = modality[ft]

    d = labels[["subject_id", "split"]].merge(d, left_on="subject_id", right_index=True, how="left")
    d = d.merge(static, on="subject_id", how="left").merge(cohort, on="subject_id", how="left")
    for cond in ["T2D", "HTN", "Dyslipid", "Obesity"]:
        d[f"idx_{cond}"] = d["cardiometa_types"].fillna("").str.split(",").apply(lambda t: cond in t)

    adm_path = os.path.join(DATA_DIR, "admissions.csv.gz")
    if os.path.exists(adm_path):
        adm = pd.read_csv(adm_path, usecols=["subject_id", "race"])
        race = adm.groupby("subject_id")["race"].agg(lambda s: s.mode().iloc[0] if len(s.mode()) else np.nan)
        d = d.merge(race.apply(_race_bucket).rename("race_bucket"), left_on="subject_id",
                    right_index=True, how="left")
    else:
        print(f"  admissions.csv.gz not found under {DATA_DIR}; race subgroups skipped")
    return d


def build_subgroups(desc: pd.DataFrame) -> dict:
    """name -> boolean mask over desc rows. Continuous cutpoints come from TRAIN patients only."""
    tr = desc[desc["split"] == "train"]
    if tr.empty:  # pooled CV OOF dir: everyone is a test patient; cutpoints use
        tr = desc  # pre-index descriptors of the whole cohort (no outcome info)
    q = lambda col, p: float(tr[col].quantile(p))
    age_lo, age_hi = q("age_at_index", 1 / 3), q("age_at_index", 2 / 3)
    sg = {
        "female": desc["female"] == 1,
        f"age < {age_lo:.0f} (young tertile)": desc["age_at_index"] < age_lo,
        f"age >= {age_hi:.0f} (old tertile)": desc["age_at_index"] >= age_hi,
        "CCI = 0": desc["cci_score"] == 0,
        "CCI >= 3": desc["cci_score"] >= 3,
        "1 index cardiometabolic condition": desc["num_cardiometa_conditions"] == 1,
        ">= 3 index cardiometabolic conditions": desc["num_cardiometa_conditions"] >= 3,
        "index dx includes T2D": desc["idx_T2D"],
        "index dx includes HTN": desc["idx_HTN"],
        "index dx includes dyslipidemia": desc["idx_Dyslipid"],
        "index dx includes obesity": desc["idx_Obesity"],
        "any pre-index ICU stay": desc["had_icu_stay"] == 1,
        f"thin history (< {q('n_facts', .5):.0f} facts, paper split)": desc["n_facts"] < q("n_facts", .5),
        f"very thin history (bottom quartile, < {q('n_facts', .25):.0f} facts)": desc["n_facts"] < q("n_facts", .25),
        f"very rich history (top quartile, >= {q('n_facts', .75):.0f} facts)": desc["n_facts"] >= q("n_facts", .75),
        f"few distinct concepts (< {q('n_concepts', .5):.0f})": desc["n_concepts"] < q("n_concepts", .5),
        "no encounter before index admission": ~desc["has_prior_encounter"].astype(bool),
        f"long history span (> {q('history_span_days', .5):.0f} days)": desc["history_span_days"] > q("history_span_days", .5),
        f"recency-heavy history (> {q('frac_recent_90d', .5):.2f} of facts in last 90d)":
            desc["frac_recent_90d"] > q("frac_recent_90d", .5),
        "history exceeds TKG 256-event window": desc["n_facts"] > 256,
        "no lab results": ~desc.get("has_lab", pd.Series(True, index=desc.index)).astype(bool),
        "no outpatient BP (OMR)": ~desc.get("has_omr_bp", pd.Series(True, index=desc.index)).astype(bool),
        "no medication orders": ~desc.get("has_prescription", pd.Series(True, index=desc.index)).astype(bool),
    }
    if "race_bucket" in desc:
        for r in ["Black", "Hispanic/Latino", "Asian", "Unknown"]:
            sg[f"race: {r}"] = desc["race_bucket"] == r
    return {k: v.fillna(False).to_numpy(bool) for k, v in sg.items()}


