def write_summary(scores, sg_summ, prof, enr, wdf, comp) -> str:
    L = ["DISCUSSION CANDIDATE FINDINGS (exploratory; see CSVs for every number)",
         f"Models available: {', '.join(f'{MODEL_LABEL[m]} ({len(s)} seed(s))' for m, s in scores.items())}", ""]

    if len(sg_summ):
        L.append("1. SUBGROUP INTERACTIONS  interaction = (A-B in subgroup) - (A-B in rest), AUROC")
        L.append("   Ranked by Wilcoxon p over cells; q = BH across the whole scan. 'A wins in sg' = cells")
        L.append("   where A beats B inside the subgroup itself in >=4/5 seeds.")
        top = sg_summ[sg_summ.pair != "xgb_vs_cox"].head(12)
        for _, r in top.iterrows():
            L.append(f"   [{r.pair}] {r.subgroup} (n={r.n_in}, median pos/cell={r.median_npos_in:.0f}): "
                     f"interaction {r.mean_interaction:+.3f}; consistent +{r.cells_consistent_pos}/-"
                     f"{r.cells_consistent_neg} of {r.n_cells} cells; p={r.wilcoxon_p:.3g}, q={r.wilcoxon_q_bh:.2g}; "
                     f"A-B inside sg {r.mean_delta_in:+.3f} (A wins {r.cells_A_wins_in_subgroup} cells)")
        L.append("")

    if len(prof):
        L.append("2. RESCUED POSITIVES (3y, diseases pooled): true positives one model ranks >=25 pct-pts higher")
        for pair, sub in prof.groupby("pair"):
            for _, r in sub[sub.group != "similar"].iterrows():
                L.append(f"   [{pair}] {r.group}: n={r.n}, median facts={r.median_n_facts:.0f}, "
                         f"concepts={r.median_n_concepts:.0f}, span={r.median_history_span_days:.0f}d, "
                         f"age={r.median_age_at_index:.0f}, CCI={r.median_cci_score:.0f}")
        if len(enr):
            sig = enr[(enr.kind == "profile") & (enr.p < 0.05)]
            for _, r in sig.iterrows():
                L.append(f"   [{r.pair}] profile differs on {r.feature}: {r.a_value:.2f} vs {r.b_value:.2f} (p={r.p:.3g})")
            conc = enr[(enr.kind == "concept")].sort_values("p").groupby("pair").head(6)
            for _, r in conc.iterrows():
                L.append(f"   [{r.pair}] concept {r.feature} ({r.fact_type}): {r.a_value:.0%} vs {r.b_value:.0%}, "
                         f"OR={r.odds_ratio:.2f}, p={r.p:.2g}, q={r.q_bh:.2g}")
        L.append("")

    if len(wdf):
        L.append("3. WHICH DISEASE FIRST (events within 5y; argmax of within-disease percentile risk)")
        for _, r in wdf.iterrows():
            extra = ""
            if "acc_minus_cox_seedavg" in r and pd.notna(r.get("acc_minus_cox_seedavg")):
                extra = (f"; seed-avg vs Cox {r.acc_minus_cox_seedavg:+.3f} "
                         f"[{r.acc_minus_cox_ci_lo:+.3f}, {r.acc_minus_cox_ci_hi:+.3f}]")
            L.append(f"   {MODEL_LABEL[r.model]}: top-1 acc {r.top1_acc_mean:.3f}"
                     f" (sd {0 if pd.isna(r.top1_acc_std) else r.top1_acc_std:.3f}), macro OvR AUC "
                     f"{r.macro_ovr_auc_mean:.3f}, majority-class {r.majority_class_acc:.3f}{extra}")
        L.append("")

    if len(comp):
        L.append("4. COMPLEMENTARITY (rank-average with Cox vs Cox alone)")
        for m, sub in comp.groupby("partner"):
            L.append(f"   Cox+{MODEL_LABEL[m]}: mean gain {sub.ensemble_minus_cox.mean():+.4f}, "
                     f"gains in {(sub.ensemble_minus_cox > 0).sum()}/{len(sub)} cells, DeLong p<0.05 "
                     f"(gain) in {((sub.delong_p_ens_vs_cox < .05) & (sub.ensemble_minus_cox > 0)).sum()}; "
                     f"median Spearman with Cox {sub.spearman_with_cox.median():.2f}")
        L.append("   (Cox+XGBoost is the same-information control: a larger gain from a neural partner")
        L.append("    suggests signal the fixed-feature vector does not capture.)")
    text = "\n".join(L)
    with open(os.path.join(OUT_DIR, "summary.txt"), "w") as f:
        f.write(text + "\n")
    return text


def run() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    labels = pd.read_csv(os.path.join(MODELING_DIR, "labels.csv"))
    test = labels[labels.split == "test"].reset_index(drop=True)

    print("Loading test-set predictions...")
    scores = load_scores()
    common = set(test.subject_id)
    for by_seed in scores.values():
        for cells in by_seed.values():
            common &= set(next(iter(cells.values())).index)
    test = test[test.subject_id.isin(common)].reset_index(drop=True)
    print(f"  {len(test)} test patients scored by every available model")

    print("Building pre-index descriptors and subgroups...")
    desc = build_descriptors(labels)
    test_desc = test[["subject_id"]].merge(desc, on="subject_id", how="left")
    # Subgroup masks are built over all patients (train cutpoints), then aligned to test order.
    test_rows = pd.Series(np.arange(len(desc)), index=desc.subject_id).reindex(test.subject_id).to_numpy()
    subgroups = {k: v[test_rows] for k, v in build_subgroups(desc).items()}

    print("1/4 Subgroup interaction scan...")
    _, sg_summ = subgroup_scan(scores, test, subgroups)
    print("2/4 Rescued-positive profiling...")
    prof, enr = rescued_positives(scores, test, test_desc)
    print("3/4 Which disease first...")
    wdf = which_disease_first(scores, test)
    print("4/4 Complementarity...")
    comp = complementarity(scores, test)

    print("\n" + write_summary(scores, sg_summ, prof, enr, wdf, comp))
    print(f"\nAll outputs in {OUT_DIR}")


if __name__ == "__main__":
    run()
