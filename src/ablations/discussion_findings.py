# 2. Rescued positives: who does A catch that B misses, and what do they have? #
# --------------------------------------------------------------------------- #
def _pct_rank(scores, model, cause, h, sids, mask):
    """Seed-averaged within-eligible-population percentile rank (0..1)."""
    ranks = [cells[(cause, h)].reindex(sids).to_numpy(float)[mask] for cells in scores[model].values()]
    return np.mean([stats.rankdata(r) / len(r) for r in ranks], axis=0)


def rescued_positives(scores, test, desc, h=1095) -> tuple:
    evts, durs = test["endpoint_type"].to_numpy(), test["time_to_event_days"].to_numpy(float)
    sids = test["subject_id"].to_numpy()
    ev = read_events_table(["subject_id", "concept_node_idx"]).drop_duplicates()
    ev = ev[ev.subject_id.isin(sids)]
    names = pd.read_csv(os.path.join(MODELING_DIR, "node_metadata.csv")).set_index("node_idx")
    profile_cols = ["n_facts", "n_concepts", "history_span_days", "frac_recent_90d", "age_at_index",
                    "cci_score", "num_cardiometa_conditions", "had_icu_stay", "female", "has_prior_encounter"]

    prof_rows, enr_rows = [], []
    for a, b in [("pg", "cox"), ("tkg", "cox"), ("pg", "tkg")]:
        if a not in scores or b not in scores:
            continue
        pos = []
        for cause in CAUSES:
            y, mask = _labels_for(cause, h, evts, durs)
            gap = _pct_rank(scores, a, cause, h, sids, mask) - _pct_rank(scores, b, cause, h, sids, mask)
            pos.append(pd.DataFrame({"subject_id": sids[mask][y == 1], "cause": cause, "gap": gap[y == 1]}))
        pos = pd.concat(pos, ignore_index=True)
        pos["group"] = np.select([pos.gap >= RESCUE_GAP, pos.gap <= -RESCUE_GAP],
                                 [f"{a}-favoured", f"{b}-favoured"], "similar")
        pos = pos.merge(desc, on="subject_id", how="left")
        for grp, sub in pos.groupby("group"):
            row = {"pair": f"{a}_vs_{b}", "group": grp, "n": len(sub)}
            row.update(sub[profile_cols].astype(float).median().add_prefix("median_").to_dict())
            row.update(sub["cause"].value_counts().add_prefix("n_").to_dict())
            prof_rows.append(row)

        ga, gb = pos[pos.group == f"{a}-favoured"], pos[pos.group == f"{b}-favoured"]
        if len(ga) < 10 or len(gb) < 10:
            continue
        # Mann-Whitney on profile differences between the two rescued groups
        for col in profile_cols:
            xa, xb = ga[col].astype(float).dropna(), gb[col].astype(float).dropna()
            p = stats.mannwhitneyu(xa, xb).pvalue if len(xa) and len(xb) else np.nan
            enr_rows.append(dict(pair=f"{a}_vs_{b}", kind="profile", feature=col,
                                 a_value=xa.median(), b_value=xb.median(), p=p))
        # Concept enrichment (presence anywhere in pre-index history)
        pres = ev[ev.subject_id.isin(pd.concat([ga.subject_id, gb.subject_id]))]
        ca = pres[pres.subject_id.isin(ga.subject_id)].concept_node_idx.value_counts()
        cb = pres[pres.subject_id.isin(gb.subject_id)].concept_node_idx.value_counts()
        both = pd.concat([ca, cb], axis=1, keys=["a", "b"]).fillna(0)
        both = both[both.sum(axis=1) >= MIN_CONCEPT_SUPPORT]
        na, nb = ga.subject_id.nunique(), gb.subject_id.nunique()
        for idx, r in both.iterrows():
            tab = [[r.a, na - r.a], [r.b, nb - r.b]]
            odds, p = stats.fisher_exact(tab)
            enr_rows.append(dict(pair=f"{a}_vs_{b}", kind="concept", feature=names.concept_id.get(idx, idx),
                                 fact_type=names.fact_type.get(idx, ""), a_value=r.a / na, b_value=r.b / nb,
                                 odds_ratio=(r.a + .5) * (nb - r.b + .5) / ((na - r.a + .5) * (r.b + .5)), p=p))
    prof, enr = pd.DataFrame(prof_rows), pd.DataFrame(enr_rows)
    if len(enr):
        enr["q_bh"] = np.nan
        for (pair, kind), idx in enr.groupby(["pair", "kind"]).groups.items():
            enr.loc[idx, "q_bh"] = stats.false_discovery_control(enr.loc[idx, "p"].fillna(1))
        enr = enr.sort_values(["pair", "kind", "p"])
    prof.to_csv(os.path.join(OUT_DIR, "rescued_positive_profiles.csv"), index=False)
    enr.to_csv(os.path.join(OUT_DIR, "rescued_positive_enrichment.csv"), index=False)
    return prof, enr


# --------------------------------------------------------------------------- #
# 3. Which disease comes first?                                                #
# --------------------------------------------------------------------------- #
def which_disease_first(scores, test, h=1825) -> pd.DataFrame:
    """Among patients with an observed target event within h, accuracy of the
    argmax over within-disease percentile ranks. Percentile ranks put Cox's
    relative-risk scores and the neural CIFs on the same footing."""
    sids = test["subject_id"].to_numpy()
    ev_mask = (test.endpoint_type != "censored").to_numpy() & (test.time_to_event_days <= h).to_numpy()
    truth = test.endpoint_type.to_numpy()[ev_mask]
    prev = pd.Series(truth).value_counts(normalize=True)

    def pred_matrix(model, seed):
        cols = []
        for c in CAUSES:
            s = scores[model][seed][(c, h)].reindex(sids).to_numpy(float)
            cols.append(stats.rankdata(s)[ev_mask] / len(s))  # rank within the whole test set
        return np.vstack(cols).T

    rows, seed_avg = [], {}
    for model, by_seed in scores.items():
        mats = {s: pred_matrix(model, s) for s in by_seed}
        for seed, P in mats.items():
            pred = np.array(CAUSES)[P.argmax(1)]
            ovr = [roc_auc_score(truth == c, P[:, i]) for i, c in enumerate(CAUSES) if 0 < (truth == c).sum() < len(truth)]
            rows.append(dict(model=model, seed=seed, n_events=len(truth), top1_acc=(pred == truth).mean(),
                             macro_ovr_auc=np.mean(ovr),
                             **{f"recall_{c}": (pred[truth == c] == c).mean() for c in CAUSES}))
        seed_avg[model] = np.mean(list(mats.values()), axis=0)
    res = pd.DataFrame(rows)
    summ = res.groupby("model").agg(["mean", "std"]).drop(columns="seed")
    summ.columns = [f"{a}_{b}" for a, b in summ.columns]
    summ = summ.reset_index()
    summ["majority_class_acc"] = prev.max()

    # Paired bootstrap of top-1 accuracy difference vs Cox (seed-averaged ranks)
    if "cox" in seed_avg:
        idx = np.arange(len(truth))
        hits = {m: (np.array(CAUSES)[P.argmax(1)] == truth).astype(float) for m, P in seed_avg.items()}
        for m in seed_avg:
            if m == "cox":
                continue
            diffs = [hits[m][b].mean() - hits["cox"][b].mean()
                     for b in (RNG.choice(idx, len(idx)) for _ in range(N_BOOT))]
            lo, hi = np.percentile(diffs, [2.5, 97.5])
            summ.loc[summ.model == m, "acc_minus_cox_seedavg"] = hits[m].mean() - hits["cox"].mean()
            summ.loc[summ.model == m, "acc_minus_cox_ci_lo"] = lo
            summ.loc[summ.model == m, "acc_minus_cox_ci_hi"] = hi
    res.to_csv(os.path.join(OUT_DIR, "which_disease_first_by_seed.csv"), index=False)
    summ.to_csv(os.path.join(OUT_DIR, "which_disease_first_summary.csv"), index=False)
    return summ


# --------------------------------------------------------------------------- #
# 4. Complementarity: does rank-averaging with Cox help?                        #
# --------------------------------------------------------------------------- #
def complementarity(scores, test) -> pd.DataFrame:
    if "cox" not in scores:
        return pd.DataFrame()
    evts, durs = test["endpoint_type"].to_numpy(), test["time_to_event_days"].to_numpy(float)
    sids = test["subject_id"].to_numpy()
    rows = []
    for cause in CAUSES:
        for h in HORIZON_DAYS:
            y, mask = _labels_for(cause, h, evts, durs)
            cox = _pct_rank(scores, "cox", cause, h, sids, mask)
            for m in scores:
                if m == "cox":
                    continue
                other = _pct_rank(scores, m, cause, h, sids, mask)
                ens = (cox + other) / 2
                auc_cox, auc_ens, p = delong_test(y, cox, ens)
                rows.append(dict(cause=cause, horizon=H_LABEL[h], partner=m, n_pos=int(y.sum()),
                                 spearman_with_cox=stats.spearmanr(cox, other)[0],
                                 auc_cox=auc_cox, auc_partner_seedavg=roc_auc_score(y, other),
                                 auc_ensemble=auc_ens, ensemble_minus_cox=auc_ens - auc_cox,
                                 delong_p_ens_vs_cox=p))
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(OUT_DIR, "complementarity.csv"), index=False)
    return df


