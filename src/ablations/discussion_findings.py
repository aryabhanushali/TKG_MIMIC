# 1. Subgroup interaction scan                                                 #
# --------------------------------------------------------------------------- #
def _auc_or_nan(y, s):
    return roc_auc_score(y, s) if MIN_POS <= y.sum() < len(y) else np.nan


def subgroup_scan(scores, test, subgroups) -> tuple:
    evts, durs = test["endpoint_type"].to_numpy(), test["time_to_event_days"].to_numpy(float)
    sids = test["subject_id"].to_numpy()

    # Precompute AUC per (model, seed, cell, subgroup, in/out) once; pairs are differences of these.
    auc_rows = []
    for cause in CAUSES:
        for h in HORIZON_DAYS:
            y_full, mask = _labels_for(cause, h, evts, durs)
            for name, sg_mask in subgroups.items():
                in_m = sg_mask[mask]
                for model, by_seed in scores.items():
                    for seed, cells in by_seed.items():
                        s = cells[(cause, h)].reindex(sids).to_numpy(float)[mask]
                        auc_rows.append(dict(
                            subgroup=name, cause=cause, horizon=h, model=model, seed=seed,
                            auc_in=_auc_or_nan(y_full[in_m], s[in_m]),
                            auc_out=_auc_or_nan(y_full[~in_m], s[~in_m]),
                            n_in=int(in_m.sum()), npos_in=int(y_full[in_m].sum()),
                            npos_out=int(y_full[~in_m].sum())))
    aucs = pd.DataFrame(auc_rows)
    aucs.to_csv(os.path.join(OUT_DIR, "subgroup_auc_by_model.csv"), index=False)

    rows = []
    for a, b in PAIRS:
        if a not in scores or b not in scores:
            continue
        A = aucs[aucs.model == a].drop(columns="model")
        B = aucs[aucs.model == b].drop(columns="model")
        if len(scores[b]) == 1:  # fixed comparator: broadcast its single fit across A's seeds
            B = B.drop(columns="seed")
            m = A.merge(B, on=["subgroup", "cause", "horizon", "n_in", "npos_in", "npos_out"], suffixes=("_a", "_b"))
        else:                    # both stochastic: pair seed s with seed s
            m = A.merge(B, on=["subgroup", "cause", "horizon", "seed", "n_in", "npos_in", "npos_out"],
                        suffixes=("_a", "_b"))
        m["delta_in"] = m.auc_in_a - m.auc_in_b
        m["delta_out"] = m.auc_out_a - m.auc_out_b
        m["interaction"] = m.delta_in - m.delta_out
        m = m.dropna(subset=["interaction"])
        cell = m.groupby(["subgroup", "cause", "horizon"]).agg(
            n_in=("n_in", "first"), npos_in=("npos_in", "first"), npos_out=("npos_out", "first"),
            n_seeds=("seed", "size"),
            seeds_pos=("interaction", lambda x: int((x > 0).sum())),
            seeds_inpos=("delta_in", lambda x: int((x > 0).sum())),
            interaction=("interaction", "mean"), delta_in=("delta_in", "mean"),
            delta_out=("delta_out", "mean")).reset_index()
        cell.insert(0, "pair", f"{a}_vs_{b}")
        rows.append(cell)
    if not rows:
        return pd.DataFrame(), pd.DataFrame()
    cells = pd.concat(rows, ignore_index=True)
    agree = cells.n_seeds.clip(upper=SEED_AGREE)  # a single-seed pair needs that one seed to agree
    cells["consistent_pos"] = cells.seeds_pos >= agree
    cells["consistent_neg"] = (cells.n_seeds - cells.seeds_pos) >= agree
    cells["subgroup_wins"] = cells.seeds_inpos >= agree   # A actually beats B inside the subgroup
    cells.to_csv(os.path.join(OUT_DIR, "subgroup_interaction_cells.csv"), index=False)

    summ = cells.groupby(["pair", "subgroup"]).agg(
        n_in=("n_in", "first"), n_cells=("interaction", "size"),
        median_npos_in=("npos_in", "median"),
        mean_interaction=("interaction", "mean"), median_interaction=("interaction", "median"),
        cells_consistent_pos=("consistent_pos", "sum"), cells_consistent_neg=("consistent_neg", "sum"),
        mean_delta_in=("delta_in", "mean"), mean_delta_out=("delta_out", "mean"),
        cells_A_wins_in_subgroup=("subgroup_wins", "sum")).reset_index()
    summ = summ[(summ.n_in >= MIN_SUBGROUP_N) & (summ.n_cells >= 5)].copy()

    def _sign_p(r):
        k, n = int(r.cells_consistent_pos), int(r.cells_consistent_pos + r.cells_consistent_neg)
        return stats.binomtest(k, n, 0.5).pvalue if n else 1.0

    def _wilcoxon_p(r):
        x = cells[(cells.pair == r.pair) & (cells.subgroup == r.subgroup)].interaction
        return stats.wilcoxon(x).pvalue if (x != 0).sum() >= 5 else 1.0

    summ["sign_test_p"] = summ.apply(_sign_p, axis=1)
    summ["wilcoxon_p"] = summ.apply(_wilcoxon_p, axis=1)
    summ["wilcoxon_q_bh"] = stats.false_discovery_control(summ.wilcoxon_p)
    summ = summ.sort_values("wilcoxon_p")
    summ.to_csv(os.path.join(OUT_DIR, "subgroup_interaction_summary.csv"), index=False)
    return cells, summ


